"""Exportable, provenance-preserving evidence reports (Markdown / HTML)."""

from __future__ import annotations

import html

DISCLAIMER = ("This report lists observable visual content generated by a vision-language model and its review "
              "status. It contains no identity determination. Model confidence scores are not probabilities unless "
              "marked calibrated. Unreviewed observations must not be relied upon.")


def image_report_markdown(data: dict) -> str:
    m = data["meta"]
    lines = [f"# Evidence report: {m['uid']}", "", f"> {DISCLAIMER}", "",
             f"* Source dataset: {m['source']} (id {m['source_id']}, split {m.get('split')})",
             f"* Image file: `{m['local_path']}` (md5 {m.get('md5')})", ""]
    obs = data.get("observations", [])
    if obs:
        p = obs[0]["provenance"]
        lines += [f"* Model: {p.get('model_name')} rev {p.get('model_revision')} ({p.get('quantization')}),"
                  f" prompt {p.get('prompt_version')}, run {p.get('run_id')}", ""]
    lines += ["## Observations", "", "| Category | Label | Raw text | Attribute | Score | Calibrated | Review | Flags |",
              "|---|---|---|---|---|---|---|---|"]
    for o in obs:
        u = o["uncertainty"]
        score = u.get("combined_score") if u.get("combined_score") is not None else u.get("token_confidence")
        lines.append(f"| {o['category']} | {o['label']} | {o['raw_text']} | {o.get('attribute') or ''} | "
                     f"{'' if score is None else f'{score:.2f}'} | {u.get('calibrated')} | {o['review_status']} | "
                     f"{', '.join(u.get('image_quality_flags', []) + u.get('review_reasons', []))} |")
    agg = data.get("aggregation") or {}
    if agg.get("contradictions"):
        lines += ["", "## Consistency issues", ""]
        for c in agg["contradictions"]:
            lines.append(f"* **{c['slot']}** ({c['kind']}, {c['severity']}): {c['explanation']} values={list(c['values'])}")
    if agg.get("missing_information"):
        lines += ["", "## Not observed", "", ", ".join(agg["missing_information"])]
    if data.get("audit"):
        lines += ["", "## Review audit trail", "", "| Time | Reviewer | Action | Observation | Comment |", "|---|---|---|---|---|"]
        for a in data["audit"]:
            lines.append(f"| {a['timestamp']} | {a['reviewer_id']} | {a['action']} | {a['observation_id']} | {a['comment']} |")
    return "\n".join(lines) + "\n"


def markdown_to_html(md: str) -> str:
    """Minimal converter (headings, lists, tables, quotes) to avoid extra dependencies."""
    out, in_table = [], False
    for line in md.splitlines():
        esc = html.escape(line)
        if line.startswith("|"):
            cells = [c.strip() for c in line.strip("|").split("|")]
            if set("".join(cells)) <= set("-"):
                continue
            if not in_table:
                out.append("<table border='1' cellspacing='0' cellpadding='4'>")
                in_table = True
            out.append("<tr>" + "".join(f"<td>{html.escape(c)}</td>" for c in cells) + "</tr>")
            continue
        if in_table:
            out.append("</table>")
            in_table = False
        if line.startswith("# "):
            out.append(f"<h1>{esc[2:]}</h1>")
        elif line.startswith("## "):
            out.append(f"<h2>{esc[3:]}</h2>")
        elif line.startswith("> "):
            out.append(f"<blockquote>{esc[5:]}</blockquote>")
        elif line.startswith("* "):
            out.append(f"<li>{esc[2:]}</li>")
        elif line.strip():
            out.append(f"<p>{esc}</p>")
    if in_table:
        out.append("</table>")
    return "<html><head><meta charset='utf-8'><title>Evidence report</title></head><body style='font-family:Times New Roman'>" + "\n".join(out) + "</body></html>"
